package ders9

fun main() {
    var isim: String = "Ahmet"
    //isim = null // Derleme hatası (Kotlin Stringe Null atamamıza izin vermiyor!)

    /* peki ya gerçekten bize tip olarak null lazımsa (Nullable)
    Bu durumu Kotlin’de ifade etmek için değişkenin veri tipinin sonuna soru işareti (?) ekleriz. Buna Nullable Type (Null Olabilen Tip) denir.
    */
    var ikinciIsim: String? = "Nisa"
    ikinciIsim = null //Değişken tipi nullable old. için sorun çıkmaz





}